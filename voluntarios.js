region.addEventListener("change", function () {

    const regionSeleccionada = region.value;

    comuna.innerHTML = '<option value="">Seleccione una comuna</option>';

    if (regionSeleccionada !== "") {

        const comunas = comunasPorRegion[regionSeleccionada];

        comunas.forEach(function (nombreComuna) {

            const opcion = document.createElement("option");

            opcion.value = nombreComuna;
            opcion.textContent = nombreComuna;

            comuna.appendChild(opcion);
        });
    }
});


formulario.addEventListener("submit", function (evento) {

    evento.preventDefault();

    const nombre = document.getElementById("nombre").value.trim();
    const apellido = document.getElementById("apellido").value.trim();
    const email = document.getElementById("email").value.trim();
    const telefono = document.getElementById("telefono").value.trim();
    const direccion = document.getElementById("direccion").value.trim();

    let errores = [];


    const nombreValido = /^[a-zA-ZáéíóúÁÉÍÓÚñÑüÜ\s]{2,50}$/;
    const emailValido = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
    const telefonoValido = /^(\+?56)?\s?9\s?[0-9]{8}$/;


    if (!nombreValido.test(nombre)) {
        errores.push("El nombre debe contener solo letras y tener entre 2 y 50 caracteres.");
    }

    if (!nombreValido.test(apellido)) {
        errores.push("El apellido debe contener solo letras y tener entre 2 y 50 caracteres.");
    }

    if (!emailValido.test(email)) {
        errores.push("El correo electrónico no tiene un formato válido.");
    }

    if (!telefonoValido.test(telefono)) {
        errores.push("El teléfono debe tener un formato chileno válido, por ejemplo: +56912345678.");
    }

    if (direccion.length < 5) {
        errores.push("Debe ingresar una dirección postal válida.");
    }

    if (region.value === "") {
        errores.push("Debe seleccionar una región.");
    }

    if (comuna.value === "") {
        errores.push("Debe seleccionar una comuna.");
    }


    if (errores.length > 0) {

        alert(errores.join("\n"));

    } else {

        alert("Voluntario registrado correctamente.");

        formulario.reset();

        comuna.innerHTML = '<option value="">Seleccione primero una región</option>';
    }
});